#include <iostream>
#include <set>
//A set stores unique elements in sorted order

void printSet(const std::set<int>& s)
{
    for (int value : s)
        std::cout << value << ' ';

    std::cout << '\n';
}

int main()
{
    std::set<int> s = { 50, 20, 40, 10, 30, 20 };

    std::cout << "Initial set: ";
    printSet(s);


    // ----------------------------------------------
    // 1. insert()
    // ----------------------------------------------

    s.insert(60);

    std::cout << "After insert(60): ";
    printSet(s);


    // ----------------------------------------------
    // 2. emplace()
    // ----------------------------------------------

    s.emplace(70);

    std::cout << "After emplace(70): ";
    printSet(s);


    // ----------------------------------------------
    // 3. find()
    // ----------------------------------------------

    auto it = s.find(40);

    if (it != s.end())
        std::cout << "find(40): " << *it << '\n';


    // ----------------------------------------------
    // 4. count()
    // ----------------------------------------------

    std::cout << "count(40): " << s.count(40) << '\n';


    // ----------------------------------------------
    // 5. contains() - C++20
    // ----------------------------------------------

    std::cout << "contains(50): "
        << s.contains(50) << '\n';


    // ----------------------------------------------
    // 6. lower_bound()
    // ----------------------------------------------

    it = s.lower_bound(35);

    if (it != s.end())
        std::cout << "lower_bound(35): " << *it << '\n';


    // ----------------------------------------------
    // 7. upper_bound()
    // ----------------------------------------------

    it = s.upper_bound(40);

    if (it != s.end())
        std::cout << "upper_bound(40): " << *it << '\n';


    // ----------------------------------------------
    // 8. equal_range()
    // ----------------------------------------------

    auto range = s.equal_range(40);

    std::cout << "equal_range(40): ";

    for (auto i = range.first; i != range.second; ++i)
        std::cout << *i << ' ';

    std::cout << '\n';


    // ----------------------------------------------
    // 9. erase() using iterator
    // ----------------------------------------------

    it = s.find(30);

    if (it != s.end())
        s.erase(it);

    std::cout << "After erase(iterator): ";
    printSet(s);


    // ----------------------------------------------
    // 10. erase() using key
    // ----------------------------------------------

    s.erase(20);

    std::cout << "After erase(20): ";
    printSet(s);


    // ----------------------------------------------
    // 11. size()
    // ----------------------------------------------

    std::cout << "s.size(): " << s.size() << '\n';


    // ----------------------------------------------
    // 12. empty()
    // ----------------------------------------------

    std::cout << "s.empty(): " << s.empty() << '\n';


    // ----------------------------------------------
    // 13. max_size()
    // ----------------------------------------------

    std::cout << "s.max_size(): " << s.max_size() << '\n';


    // ----------------------------------------------
    // 14. begin/end
    // ----------------------------------------------

    std::cout << "begin() -> end(): ";

    for (auto i = s.begin(); i != s.end(); ++i)
        std::cout << *i << ' ';

    std::cout << '\n';


    // ----------------------------------------------
    // 15. reverse iteration
    // ----------------------------------------------

    std::cout << "rbegin() -> rend(): ";

    for (auto i = s.rbegin(); i != s.rend(); ++i)
        std::cout << *i << ' ';

    std::cout << '\n';


    // ----------------------------------------------
    // 16. clear()
    // ----------------------------------------------

    s.clear();

    std::cout << "After clear(): "
        << s.empty() << '\n';


    return 0;
}



