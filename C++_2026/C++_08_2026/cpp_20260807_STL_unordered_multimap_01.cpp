#include <iostream>
#include <unordered_map>
//Duplicate keys + hash table

void printUnorderedMultiMap(
    const std::unordered_multimap<int, std::string>& umm)
{
    for (const auto& [key, value] : umm)
        std::cout << key << " -> " << value << '\n';
}

int main()
{
    std::unordered_multimap<int, std::string> umm = {
        {1, "One"},
        {2, "Two"},
        {2, "TWO"},
        {3, "Three"}
    };

    printUnorderedMultiMap(umm);


    // ----------------------------------------------
    // insert()
    // ----------------------------------------------

    umm.insert({ 2, "Second Two" });


    // ----------------------------------------------
    // emplace()
    // ----------------------------------------------

    umm.emplace(4, "Four");


    // ----------------------------------------------
    // find()
    // ----------------------------------------------

    auto it = umm.find(2);

    if (it != umm.end())
        std::cout << "find(2): "
        << it->second << '\n';


    // ----------------------------------------------
    // count()
    // ----------------------------------------------

    std::cout << "count(2): "
        << umm.count(2) << '\n';


    // ----------------------------------------------
    // contains()
    // ----------------------------------------------

    std::cout << "contains(2): "
        << umm.contains(2) << '\n';


    // ----------------------------------------------
    // equal_range()
    // ----------------------------------------------

    auto range = umm.equal_range(2);

    std::cout << "equal_range(2):\n";

    for (auto i = range.first; i != range.second; ++i)
        std::cout << i->first << " -> "
        << i->second << '\n';


    // ----------------------------------------------
    // erase(iterator)
    // ----------------------------------------------

    it = umm.find(2);

    if (it != umm.end())
        umm.erase(it);


    // ----------------------------------------------
    // erase(key)
    // ----------------------------------------------

    umm.erase(2);


    // ----------------------------------------------
    // bucket_count()
    // ----------------------------------------------

    std::cout << "bucket_count(): "
        << umm.bucket_count() << '\n';


    // ----------------------------------------------
    // load_factor()
    // ----------------------------------------------

    std::cout << "load_factor(): "
        << umm.load_factor() << '\n';


    // ----------------------------------------------
    // size()
    // ----------------------------------------------

    std::cout << "umm.size(): "
        << umm.size() << '\n';


    // ----------------------------------------------
    // empty()
    // ----------------------------------------------

    std::cout << "umm.empty(): "
        << umm.empty() << '\n';


    // ----------------------------------------------
    // max_size()
    // ----------------------------------------------

    std::cout << "umm.max_size(): "
        << umm.max_size() << '\n';


    // ----------------------------------------------
    // clear()
    // ----------------------------------------------

    umm.clear();

    std::cout << "After clear(): "
        << umm.empty() << '\n';


    return 0;
}



