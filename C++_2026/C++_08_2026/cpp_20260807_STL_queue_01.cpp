#include <iostream>
#include <queue>

void printQueue(std::queue<int> q)
{
    while (!q.empty())
    {
        std::cout << q.front() << ' ';
        q.pop();
    }

    std::cout << '\n';
}

int main()
{
    // ----------------------------------------------
    // 1. Declaration
    // ----------------------------------------------

    std::queue<int> q;

    q.push(10);
    q.push(20);
    q.push(30);
    q.push(40);
    q.push(50);

    std::cout << "Initial queue: ";
    printQueue(q);


    // ----------------------------------------------
    // 2. front()
    // ----------------------------------------------

    std::cout << "q.front() : " << q.front() << '\n';


    // ----------------------------------------------
    // 3. back()
    // ----------------------------------------------

    std::cout << "q.back()  : " << q.back() << '\n';


    // ----------------------------------------------
    // 4. Modify front()
    // ----------------------------------------------

    q.front() = 100;

    std::cout << "After q.front() = 100: ";
    printQueue(q);


    // ----------------------------------------------
    // 5. Modify back()
    // ----------------------------------------------

    q.back() = 500;

    std::cout << "After q.back() = 500: ";
    printQueue(q);


    // ----------------------------------------------
    // 6. Capacity
    // ----------------------------------------------

    std::cout << "q.empty()    : " << q.empty() << '\n';
    std::cout << "q.size()     : " << q.size() << '\n';
    std::cout << "q.max_size() : " << q.max_size() << '\n';


    // ----------------------------------------------
    // 7. push()
    // ----------------------------------------------

    q.push(60);

    std::cout << "After push(60): ";
    printQueue(q);


    // ----------------------------------------------
    // 8. emplace()
    // ----------------------------------------------

    q.emplace(70);

    std::cout << "After emplace(70): ";
    printQueue(q);


    // ----------------------------------------------
    // 9. pop()
    // ----------------------------------------------

    q.pop();

    std::cout << "After pop(): ";
    printQueue(q);


    // ----------------------------------------------
    // 10. swap()
    // ----------------------------------------------

    std::queue<int> q2;

    q2.push(1000);
    q2.push(2000);

    q.swap(q2);

    std::cout << "After swap():\n";

    std::cout << "q  : ";
    printQueue(q);

    std::cout << "q2 : ";
    printQueue(q2);


    // ----------------------------------------------
    // 11. clear()
    // ----------------------------------------------

    // queue has NO clear() member function.
    // We can empty it using pop():

    while (!q.empty())
        q.pop();

    std::cout << "After clearing using pop():\n";
    std::cout << "q.empty() : " << q.empty() << '\n';


    return 0;
}



