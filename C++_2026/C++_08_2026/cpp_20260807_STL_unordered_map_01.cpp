#include <iostream>
#include <unordered_map>
//Unique keys, hash-based lookup

void printUnorderedMap(
    const std::unordered_map<int, std::string>& um)
{
    for (const auto& [key, value] : um)
        std::cout << key << " -> " << value << '\n';
}

int main()
{
    std::unordered_map<int, std::string> um = {
        {1, "One"},
        {2, "Two"},
        {3, "Three"}
    };

    printUnorderedMap(um);


    // --------------------------------------------------
    // operator[]
    // --------------------------------------------------

    std::cout << "um[2]: "
        << um[2] << '\n';


    // --------------------------------------------------
    // Modify
    // --------------------------------------------------

    um[2] = "TWO";

    printUnorderedMap(um);


    // --------------------------------------------------
    // at()
    // --------------------------------------------------

    std::cout << "um.at(1): "
        << um.at(1) << '\n';


    // --------------------------------------------------
    // insert()
    // --------------------------------------------------

    um.insert({ 4, "Four" });


    // --------------------------------------------------
    // emplace()
    // --------------------------------------------------

    um.emplace(5, "Five");


    // --------------------------------------------------
    // insert_or_assign()
    // --------------------------------------------------

    um.insert_or_assign(3, "THREE");


    // --------------------------------------------------
    // try_emplace()
    // --------------------------------------------------

    um.try_emplace(6, "Six");


    // --------------------------------------------------
    // find()
    // --------------------------------------------------

    auto it = um.find(3);

    if (it != um.end())
        std::cout << "find(3): "
        << it->second << '\n';


    // --------------------------------------------------
    // count()
    // --------------------------------------------------

    std::cout << "count(3): "
        << um.count(3) << '\n';


    // --------------------------------------------------
    // contains()
    // --------------------------------------------------

    std::cout << "contains(3): "
        << um.contains(3) << '\n';


    // --------------------------------------------------
    // erase(iterator)
    // --------------------------------------------------

    it = um.find(2);

    if (it != um.end())
        um.erase(it);


    // --------------------------------------------------
    // erase(key)
    // --------------------------------------------------

    um.erase(4);


    // --------------------------------------------------
    // bucket_count()
    // --------------------------------------------------

    std::cout << "bucket_count(): "
        << um.bucket_count() << '\n';


    // --------------------------------------------------
    // load_factor()
    // --------------------------------------------------

    std::cout << "load_factor(): "
        << um.load_factor() << '\n';


    // --------------------------------------------------
    // size()
    // --------------------------------------------------

    std::cout << "um.size(): "
        << um.size() << '\n';


    // --------------------------------------------------
    // empty()
    // --------------------------------------------------

    std::cout << "um.empty(): "
        << um.empty() << '\n';


    // --------------------------------------------------
    // max_size()
    // --------------------------------------------------

    std::cout << "um.max_size(): "
        << um.max_size() << '\n';


    // --------------------------------------------------
    // clear()
    // --------------------------------------------------

    um.clear();

    std::cout << "After clear(): "
        << um.empty() << '\n';


    return 0;
}

