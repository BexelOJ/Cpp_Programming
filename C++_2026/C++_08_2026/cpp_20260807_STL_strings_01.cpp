#include <iostream>
#include <string>

int main()
{
    // ----------------------------------------------
    // 1. Declaration and initialization
    // ----------------------------------------------

    std::string str = "Hello";

    std::cout << "Initial string: "
        << str << '\n';


    // ----------------------------------------------
    // 2. operator[]
    // ----------------------------------------------

    std::cout << "str[0]: "
        << str[0] << '\n';


    // ----------------------------------------------
    // 3. at()
    // ----------------------------------------------

    std::cout << "str.at(1): "
        << str.at(1) << '\n';


    // ----------------------------------------------
    // 4. front()
    // ----------------------------------------------

    std::cout << "str.front(): "
        << str.front() << '\n';


    // ----------------------------------------------
    // 5. back()
    // ----------------------------------------------

    std::cout << "str.back(): "
        << str.back() << '\n';


    // ----------------------------------------------
    // 6. Modify character
    // ----------------------------------------------

    str[0] = 'h';

    std::cout << "After str[0] = 'h': "
        << str << '\n';


    // ----------------------------------------------
    // 7. begin() / end()
    // ----------------------------------------------

    std::cout << "begin() -> end(): ";

    for (auto it = str.begin(); it != str.end(); ++it)
        std::cout << *it;

    std::cout << '\n';


    // ----------------------------------------------
    // 8. rbegin() / rend()
    // ----------------------------------------------

    std::cout << "rbegin() -> rend(): ";

    for (auto it = str.rbegin(); it != str.rend(); ++it)
        std::cout << *it;

    std::cout << '\n';


    // ----------------------------------------------
    // 9. cbegin() / cend()
    // ----------------------------------------------

    std::cout << "cbegin() -> cend(): ";

    for (auto it = str.cbegin(); it != str.cend(); ++it)
        std::cout << *it;

    std::cout << '\n';


    // ----------------------------------------------
    // 10. size()
    // ----------------------------------------------

    std::cout << "str.size(): "
        << str.size() << '\n';


    // ----------------------------------------------
    // 11. length()
    // ----------------------------------------------

    std::cout << "str.length(): "
        << str.length() << '\n';


    // ----------------------------------------------
    // 12. empty()
    // ----------------------------------------------

    std::cout << "str.empty(): "
        << str.empty() << '\n';


    // ----------------------------------------------
    // 13. max_size()
    // ----------------------------------------------

    std::cout << "str.max_size(): "
        << str.max_size() << '\n';


    // ----------------------------------------------
    // 14. capacity()
    // ----------------------------------------------

    std::cout << "str.capacity(): "
        << str.capacity() << '\n';


    // ----------------------------------------------
    // 15. reserve()
    // ----------------------------------------------

    str.reserve(100);

    std::cout << "After reserve(100):\n";
    std::cout << "capacity(): "
        << str.capacity() << '\n';


    // ----------------------------------------------
    // 16. append()
    // ----------------------------------------------

    str.append(" World");

    std::cout << "After append(): "
        << str << '\n';


    // ----------------------------------------------
    // 17. push_back()
    // ----------------------------------------------

    str.push_back('!');

    std::cout << "After push_back(): "
        << str << '\n';


    // ----------------------------------------------
    // 18. pop_back()
    // ----------------------------------------------

    str.pop_back();

    std::cout << "After pop_back(): "
        << str << '\n';


    // ----------------------------------------------
    // 19. insert()
    // ----------------------------------------------

    str.insert(5, " C++");

    std::cout << "After insert(): "
        << str << '\n';


    // ----------------------------------------------
    // 20. erase()
    // ----------------------------------------------

    str.erase(5, 4);

    std::cout << "After erase(): "
        << str << '\n';


    // ----------------------------------------------
    // 21. replace()
    // ----------------------------------------------

    str.replace(0, 5, "Hi");

    std::cout << "After replace(): "
        << str << '\n';


    // ----------------------------------------------
    // 22. substr()
    // ----------------------------------------------

    std::string sub = str.substr(0, 2);

    std::cout << "substr(): "
        << sub << '\n';


    // ----------------------------------------------
    // 23. find()
    // ----------------------------------------------

    std::size_t pos = str.find("World");

    if (pos != std::string::npos)
        std::cout << "World found at index: "
        << pos << '\n';


    // ----------------------------------------------
    // 24. rfind()
    // ----------------------------------------------

    pos = str.rfind("l");

    if (pos != std::string::npos)
        std::cout << "Last 'l' at index: "
        << pos << '\n';


    // ----------------------------------------------
    // 25. compare()
    // ----------------------------------------------

    std::string str2 = "Hello";

    std::cout << "compare(): "
        << str.compare(str2) << '\n';


    // ----------------------------------------------
    // 26. c_str()
    // ----------------------------------------------

    const char* ptr = str.c_str();

    std::cout << "c_str(): "
        << ptr << '\n';


    // ----------------------------------------------
    // 27. data()
    // ----------------------------------------------

    std::cout << "data(): "
        << str.data() << '\n';


    // ----------------------------------------------
    // 28. clear()
    // ----------------------------------------------

    str.clear();

    std::cout << "After clear():\n";

    std::cout << "str.empty(): "
        << str.empty() << '\n';

    std::cout << "str.size(): "
        << str.size() << '\n';


    return 0;
}



