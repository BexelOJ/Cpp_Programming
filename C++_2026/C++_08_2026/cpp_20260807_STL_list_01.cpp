#include <iostream>
#include <list>

void printList(const std::list<int>& l)
{
    for (int value : l)
        std::cout << value << ' ';

    std::cout << '\n';
}

int main()
{
    // --------------------------------------------------
    // 1. Declaration and initialization
    // --------------------------------------------------

    std::list<int> l = { 10, 20, 30, 40, 50 };

    std::cout << "Initial list: ";
    printList(l);


    // --------------------------------------------------
    // 2. Element access
    // --------------------------------------------------

    std::cout << "l.front() : " << l.front() << '\n';
    std::cout << "l.back()  : " << l.back() << '\n';


    // --------------------------------------------------
    // 3. Modify front and back
    // --------------------------------------------------

    l.front() = 100;
    l.back() = 500;

    std::cout << "After modifying front/back: ";
    printList(l);


    // --------------------------------------------------
    // 4. begin() / end()
    // --------------------------------------------------

    std::cout << "begin() -> end(): ";

    for (auto it = l.begin(); it != l.end(); ++it)
        std::cout << *it << ' ';

    std::cout << '\n';


    // --------------------------------------------------
    // 5. rbegin() / rend()
    // --------------------------------------------------

    std::cout << "rbegin() -> rend(): ";

    for (auto it = l.rbegin(); it != l.rend(); ++it)
        std::cout << *it << ' ';

    std::cout << '\n';


    // --------------------------------------------------
    // 6. cbegin() / cend()
    // --------------------------------------------------

    std::cout << "cbegin() -> cend(): ";

    for (auto it = l.cbegin(); it != l.cend(); ++it)
        std::cout << *it << ' ';

    std::cout << '\n';


    // --------------------------------------------------
    // 7. crbegin() / crend()
    // --------------------------------------------------

    std::cout << "crbegin() -> crend(): ";

    for (auto it = l.crbegin(); it != l.crend(); ++it)
        std::cout << *it << ' ';

    std::cout << '\n';


    // --------------------------------------------------
    // 8. Capacity
    // --------------------------------------------------

    std::cout << "l.empty()    : " << l.empty() << '\n';
    std::cout << "l.size()     : " << l.size() << '\n';
    std::cout << "l.max_size() : " << l.max_size() << '\n';


    // --------------------------------------------------
    // 9. push_back()
    // --------------------------------------------------

    l.push_back(60);

    std::cout << "After push_back(60): ";
    printList(l);


    // --------------------------------------------------
    // 10. push_front()
    // --------------------------------------------------

    l.push_front(5);

    std::cout << "After push_front(5): ";
    printList(l);


    // --------------------------------------------------
    // 11. emplace_back()
    // --------------------------------------------------

    l.emplace_back(70);

    std::cout << "After emplace_back(70): ";
    printList(l);


    // --------------------------------------------------
    // 12. emplace_front()
    // --------------------------------------------------

    l.emplace_front(1);

    std::cout << "After emplace_front(1): ";
    printList(l);


    // --------------------------------------------------
    // 13. insert()
    // --------------------------------------------------

    auto it = l.begin();
    std::advance(it, 2);

    l.insert(it, 999);

    std::cout << "After insert(999): ";
    printList(l);


    // --------------------------------------------------
    // 14. erase()
    // --------------------------------------------------

    it = l.begin();
    std::advance(it, 2);

    l.erase(it);

    std::cout << "After erase(): ";
    printList(l);


    // --------------------------------------------------
    // 15. pop_back()
    // --------------------------------------------------

    l.pop_back();

    std::cout << "After pop_back(): ";
    printList(l);


    // --------------------------------------------------
    // 16. pop_front()
    // --------------------------------------------------

    l.pop_front();

    std::cout << "After pop_front(): ";
    printList(l);


    // --------------------------------------------------
    // 17. resize()
    // --------------------------------------------------

    l.resize(10);

    std::cout << "After resize(10): ";
    printList(l);


    // --------------------------------------------------
    // 18. resize() with value
    // --------------------------------------------------

    l.resize(12, 500);

    std::cout << "After resize(12, 500): ";
    printList(l);


    // --------------------------------------------------
    // 19. assign()
    // --------------------------------------------------

    l.assign(5, 1000);

    std::cout << "After assign(5, 1000): ";
    printList(l);


    // --------------------------------------------------
    // 20. remove()
    // --------------------------------------------------

    l.assign({ 10, 20, 30, 20, 40 });

    l.remove(20);

    std::cout << "After remove(20): ";
    printList(l);


    // --------------------------------------------------
    // 21. remove_if()
    // --------------------------------------------------

    l.remove_if([](int value)
        {
            return value > 25;
        });

    std::cout << "After remove_if(value > 25): ";
    printList(l);


    // --------------------------------------------------
    // 22. reverse()
    // --------------------------------------------------

    l.reverse();

    std::cout << "After reverse(): ";
    printList(l);


    // --------------------------------------------------
    // 23. sort()
    // --------------------------------------------------

    l.assign({ 50, 10, 40, 20, 30 });

    l.sort();

    std::cout << "After sort(): ";
    printList(l);


    // --------------------------------------------------
    // 24. unique()
    // --------------------------------------------------

    l.assign({ 10, 10, 20, 20, 30 });

    l.unique();

    std::cout << "After unique(): ";
    printList(l);


    // --------------------------------------------------
    // 25. swap()
    // --------------------------------------------------

    std::list<int> l2 = { 100, 200, 300 };

    l.swap(l2);

    std::cout << "After swap():\n";

    std::cout << "l  : ";
    printList(l);

    std::cout << "l2 : ";
    printList(l2);


    // --------------------------------------------------
    // 26. clear()
    // --------------------------------------------------

    l.clear();

    std::cout << "After clear():\n";
    std::cout << "l.size()  : " << l.size() << '\n';
    std::cout << "l.empty() : " << l.empty() << '\n';


    return 0;
}



