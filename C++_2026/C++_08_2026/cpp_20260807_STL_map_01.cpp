#include <iostream>
#include <map>
//map stores key-value pairs and keys are unique

void printMap(const std::map<int, std::string>& m)
{
    for (const auto& [key, value] : m)
        std::cout << key << " -> " << value << '\n';
}

int main()
{
    // ----------------------------------------------
    // 1. Declaration
    // ----------------------------------------------

    std::map<int, std::string> m = {
        {3, "Three"},
        {1, "One"},
        {2, "Two"}
    };

    printMap(m);


    // ----------------------------------------------
    // 2. operator[]
    // ----------------------------------------------

    std::cout << "m[2]: "
        << m[2] << '\n';


    // ----------------------------------------------
    // 3. Modify using operator[]
    // ----------------------------------------------

    m[2] = "TWO";

    std::cout << "After m[2] = TWO:\n";
    printMap(m);


    // ----------------------------------------------
    // 4. at()
    // ----------------------------------------------

    std::cout << "m.at(1): "
        << m.at(1) << '\n';


    // ----------------------------------------------
    // 5. insert()
    // ----------------------------------------------

    m.insert({ 4, "Four" });

    std::cout << "After insert():\n";
    printMap(m);


    // ----------------------------------------------
    // 6. emplace()
    // ----------------------------------------------

    m.emplace(5, "Five");

    std::cout << "After emplace():\n";
    printMap(m);


    // ----------------------------------------------
    // 7. insert_or_assign()
    // ----------------------------------------------

    m.insert_or_assign(3, "THREE");

    std::cout << "After insert_or_assign():\n";
    printMap(m);


    // ----------------------------------------------
    // 8. try_emplace()
    // ----------------------------------------------

    m.try_emplace(6, "Six");

    std::cout << "After try_emplace():\n";
    printMap(m);


    // ----------------------------------------------
    // 9. find()
    // ----------------------------------------------

    auto it = m.find(3);

    if (it != m.end())
        std::cout << "find(3): "
        << it->second << '\n';


    // ----------------------------------------------
    // 10. count()
    // ----------------------------------------------

    std::cout << "count(3): "
        << m.count(3) << '\n';


    // ----------------------------------------------
    // 11. contains()
    // ----------------------------------------------

    std::cout << "contains(3): "
        << m.contains(3) << '\n';


    // ----------------------------------------------
    // 12. lower_bound()
    // ----------------------------------------------

    it = m.lower_bound(3);

    if (it != m.end())
        std::cout << "lower_bound(3): "
        << it->first << '\n';


    // ----------------------------------------------
    // 13. upper_bound()
    // ----------------------------------------------

    it = m.upper_bound(3);

    if (it != m.end())
        std::cout << "upper_bound(3): "
        << it->first << '\n';


    // ----------------------------------------------
    // 14. equal_range()
    // ----------------------------------------------

    auto range = m.equal_range(3);

    for (auto i = range.first; i != range.second; ++i)
        std::cout << "equal_range: "
        << i->first << " -> "
        << i->second << '\n';


    // ----------------------------------------------
    // 15. erase(iterator)
    // ----------------------------------------------

    it = m.find(2);

    if (it != m.end())
        m.erase(it);

    std::cout << "After erase(iterator):\n";
    printMap(m);


    // ----------------------------------------------
    // 16. erase(key)
    // ----------------------------------------------

    m.erase(4);

    std::cout << "After erase(4):\n";
    printMap(m);


    // ----------------------------------------------
    // 17. size / empty / max_size
    // ----------------------------------------------

    std::cout << "m.size(): "
        << m.size() << '\n';

    std::cout << "m.empty(): "
        << m.empty() << '\n';

    std::cout << "m.max_size(): "
        << m.max_size() << '\n';


    // ----------------------------------------------
    // 18. Iterators
    // ----------------------------------------------

    std::cout << "begin() -> end():\n";

    for (auto i = m.begin(); i != m.end(); ++i)
        std::cout << i->first << " -> "
        << i->second << '\n';


    // ----------------------------------------------
    // 19. clear()
    // ----------------------------------------------

    m.clear();

    std::cout << "After clear(): "
        << m.empty() << '\n';


    return 0;
}



