#include <iostream>
#include <stack>

void printStack(std::stack<int> s)
{
    while (!s.empty())
    {
        std::cout << s.top() << ' ';
        s.pop();
    }

    std::cout << '\n';
}

int main()
{
    // ----------------------------------------------
    // 1. Declaration
    // ----------------------------------------------

    std::stack<int> s;

    s.push(10);
    s.push(20);
    s.push(30);

    std::cout << "Initial stack: ";
    printStack(s);


    // ----------------------------------------------
    // 2. top()
    // ----------------------------------------------

    std::cout << "s.top() : " << s.top() << '\n';


    // ----------------------------------------------
    // 3. Modify top()
    // ----------------------------------------------

    s.top() = 100;

    std::cout << "After s.top() = 100: ";
    printStack(s);


    // ----------------------------------------------
    // 4. push()
    // ----------------------------------------------

    s.push(40);

    std::cout << "After push(40): ";
    printStack(s);


    // ----------------------------------------------
    // 5. emplace()
    // ----------------------------------------------

    s.emplace(50);

    std::cout << "After emplace(50): ";
    printStack(s);


    // ----------------------------------------------
    // 6. pop()
    // ----------------------------------------------

    s.pop();

    std::cout << "After pop(): ";
    printStack(s);


    // ----------------------------------------------
    // 7. size()
    // ----------------------------------------------

    std::cout << "s.size() : " << s.size() << '\n';


    // ----------------------------------------------
    // 8. empty()
    // ----------------------------------------------

    std::cout << "s.empty() : " << s.empty() << '\n';


    // ----------------------------------------------
    // 9. max_size()
    // ----------------------------------------------

    std::cout << "s.max_size() : " << s.max_size() << '\n';


    // ----------------------------------------------
    // 10. swap()
    // ----------------------------------------------

    std::stack<int> s2;

    s2.push(1000);
    s2.push(2000);

    s.swap(s2);

    std::cout << "After swap():\n";

    std::cout << "s  : ";
    printStack(s);

    std::cout << "s2 : ";
    printStack(s2);


    return 0;
}



